ASSESSMENT_AGENT_PROMPT = """
You are the Assessment Specialist Agent of TCO
(Teacher Co-Worker).

Your responsibility is to create a multiple-choice
assessment from the task assigned by the Master Agent.

You are a specialist worker.

The Master Agent has already understood the teacher's
request and assigned this task to you.

You do NOT:
- communicate directly with the teacher
- decide whether this task should exist
- perform unrelated teacher work
- approve your own assessment

Your output will be independently checked by the
Assessment Review Agent.

==================================================
MCQ REQUIREMENTS
==================================================

Generate exactly the requested number of questions.

Every question must:

1. Have exactly four options.
2. Have exactly one correct option.
3. Have one unambiguous answer.
4. Be appropriate for the requested class.
5. Be relevant to the requested topic.
6. Avoid duplicate or near-duplicate questions.
7. Avoid trick questions unless explicitly requested.

The claimed correct_option must point to the option
that is actually correct.

Do NOT guess the correct option.

==================================================
GROUNDING POLICY
==================================================

When generation_mode = source_grounded:

Use ONLY the supplied retrieved source material.

Do not introduce unsupported facts from general knowledge.

When generation_mode = llm_generated:

General knowledge may be used because the teacher
explicitly allowed AI-generated content.

Never fabricate:
- source references
- URLs
- citations
- source claims

==================================================
REGENERATION
==================================================

If previous review feedback is supplied:

- Carefully inspect every reported problem.
- Fix the reported problem.
- Recheck all questions.
- Do not blindly change unrelated questions.
- Ensure the new assessment remains internally consistent.

==================================================
OUTPUT
==================================================

Return only the structured assessment.

Do not return markdown.
Do not return commentary.
Do not return review text.
"""


# ============================================================
# ASSESSMENT AGENT
# ============================================================


class AssessmentAgent(BaseAgent):

    name = "assessment_agent"

    description = (
        "Creates multiple-choice assessments from approved "
        "grounded material or explicitly permitted AI knowledge."
    )

    capabilities = (
        "assessment.create",
        "assessment.generate_mcq",
    )

    def __init__(self):
        self.model = get_chat_model().with_structured_output(
            MCQAssessment
        )

    # ========================================================
    # MAIN ENTRY POINT
    # ========================================================

    def run(
        self,
        state: TCOState,
        task: Task | None = None,
    ) -> TCOState:

        # ----------------------------------------------------
        # Task validation
        # ----------------------------------------------------

        if task is None:
            return {
                **state,
                "status": "error",
                "error_code": "ASSESSMENT_TASK_MISSING",
                "error_message": (
                    "Assessment Agent requires an assigned task."
                ),
            }

        task_input = self._get_task_input(task)

        # ----------------------------------------------------
        # Extract requirements
        # ----------------------------------------------------

        topic = self._clean(
            task_input.get("topic")
        )

        chapter = self._clean(
            task_input.get("chapter")
        )

        subject = self._clean(
            task_input.get("subject")
        )

        class_level = self._clean(
            task_input.get("class_level")
        )

        question_count = task_input.get(
            "question_count"
        )

        total_marks = task_input.get(
            "marks"
        )

        generation_mode = task_input.get(
            "generation_mode",
            "source_grounded",
        )

        # ----------------------------------------------------
        # Previous review feedback
        # ----------------------------------------------------

        review_feedback = (
            task_input.get(
                "review_feedback",
                "",
            )
            or ""
        ).strip()

        attempt = task_input.get(
            "attempt",
            1,
        )

        # ----------------------------------------------------
        # Validate mandatory requirements
        # ----------------------------------------------------

        missing = []

        if not topic and not chapter:
            missing.append("topic")

        if question_count is None:
            missing.append("question_count")

        if total_marks is None:
            missing.append("marks")

        if missing:
            return {
                **state,
                "status": "error",
                "error_code": (
                    "ASSESSMENT_REQUIREMENTS_MISSING"
                ),
                "error_message": (
                    "Missing required assessment information: "
                    + ", ".join(missing)
                ),
            }

        if not isinstance(
            question_count,
            int,
        ) or question_count <= 0:
            return {
                **state,
                "status": "error",
                "error_code": "INVALID_QUESTION_COUNT",
                "error_message": (
                    "Question count must be a positive integer."
                ),
            }

        if not isinstance(
            total_marks,
            int,
        ) or total_marks <= 0:
            return {
                **state,
                "status": "error",
                "error_code": "INVALID_TOTAL_MARKS",
                "error_message": (
                    "Total marks must be a positive integer."
                ),
            }

        # ----------------------------------------------------
        # MCQ prototype rule
        #
        # Every question has equal marks.
        # ----------------------------------------------------

        if total_marks % question_count != 0:
            return {
                **state,
                "status": "needs_clarification",
                "error_code": (
                    "MCQ_MARK_DISTRIBUTION_INVALID"
                ),
                "error_message": (
                    "For the current MCQ prototype, total marks "
                    "must be evenly divisible by question count."
                ),
                "clarification_message": (
                    f"{question_count} questions ko equal marks "
                    f"dene ke liye total marks "
                    f"{question_count} se evenly divisible "
                    f"hona chahiye."
                ),
            }

        marks_per_question = (
            total_marks // question_count
        )

        # ----------------------------------------------------
        # Source / grounding context
        # ----------------------------------------------------

        retrieved_context = (
            state.get(
                "retrieved_context",
                "",
            )
            or ""
        ).strip()
        original_context_length = len(retrieved_context)
        retrieved_context = _bound_retrieved_context(retrieved_context)
        logger.info(
            "Assessment grounded context bounded: original_chars=%d bounded_chars=%d",
            original_context_length,
            len(retrieved_context),
        )

        source_references = list(
            state.get(
                "source_references",
                [],
            )
            or []
        )

        source_approved = bool(
            state.get(
                "source_approved",
                False,
            )
        )

        source_status = state.get(
            "source_status"
        )

        # ----------------------------------------------------
        # Source-grounded validation
        # ----------------------------------------------------

        if generation_mode == "source_grounded":

            if not retrieved_context:
                return {
                    **state,
                    "status": "waiting_for_source",
                    "error_code": (
                        "ASSESSMENT_SOURCE_REQUIRED"
                    ),
                    "error_message": (
                        "No grounded material is available "
                        "for assessment generation."
                    ),
                    "clarification_message": (
                        "Approved source material is required "
                        "before I can generate the assessment."
                    ),
                    "source_status": (
                        source_status
                        or "source_required"
                    ),
                    "approval_required": True,
                    "approval_type": "source",
                }

            if (
                source_references
                and not source_approved
            ):
                return {
                    **state,
                    "status": "waiting_for_teacher",
                    "error_code": (
                        "SOURCE_NOT_APPROVED"
                    ),
                    "error_message": (
                        "The assessment source has not "
                        "been approved."
                    ),
                    "clarification_message": (
                        "Please approve the source before "
                        "generating the assessment."
                    ),
                    "approval_required": True,
                    "approval_type": "source",
                    "approval_status": "pending",
                }

        # ----------------------------------------------------
        # Context section
        # ----------------------------------------------------

        if generation_mode == "source_grounded":

            context_section = f"""
==================================================
SOURCE-GROUNDED MODE
==================================================

Use ONLY the following retrieved material:

---------------- SOURCE MATERIAL ----------------

{retrieved_context}

-------------- END SOURCE MATERIAL --------------
"""

        else:

            context_section = """
==================================================
AI-GENERATED MODE
==================================================

The teacher explicitly allowed general AI knowledge.

No external source is required.
"""

        # ----------------------------------------------------
        # Review feedback section
        # ----------------------------------------------------

        if review_feedback:

            feedback_section = f"""
==================================================
PREVIOUS REVIEW FEEDBACK
==================================================

This is regeneration attempt {attempt}.

The previous assessment was rejected by the
Assessment Review Agent.

You MUST correct the reported problems.

Previous review feedback:

{review_feedback}

==================================================
END PREVIOUS REVIEW FEEDBACK
==================================================
"""

        else:

            feedback_section = """
==================================================
FIRST GENERATION
==================================================

There is no previous review feedback.
Generate the initial assessment carefully.
"""

        # ----------------------------------------------------
        # Build generation prompt
        # ----------------------------------------------------

        topic_value = topic or chapter

        generation_prompt = f"""
{ASSESSMENT_AGENT_PROMPT}

==================================================
ASSESSMENT REQUIREMENTS
==================================================

Topic:
{topic_value}

Subject:
{subject or "Not specified"}

Class:
{class_level or "Not specified"}

Number of questions:
{question_count}

Total marks:
{total_marks}

Marks per question:
{marks_per_question}

Generation mode:
{generation_mode}

{context_section}

{feedback_section}

==================================================
FINAL CHECK BEFORE RETURNING
==================================================

Generate exactly {question_count} questions.

Every question:
- has exactly 4 options
- has exactly 1 correct option
- has an actually correct correct_option
- is relevant to {topic_value}
- is suitable for class {class_level or "the requested level"}
- is not duplicated

Every question carries exactly
{marks_per_question} mark(s).

Return only the structured assessment.
"""
        logger.info(
            "Assessment generation prompt prepared: prompt_chars=%d context_chars=%d",
            len(generation_prompt),
            len(retrieved_context),
        )

        # ----------------------------------------------------
        # LLM generation
        # ----------------------------------------------------

        try:

            assessment: MCQAssessment = self.model.invoke(
                generation_prompt
            )

        except Exception as exc:

            return {
                **state,
                "status": "error",
                "error_code": (
                    "ASSESSMENT_GENERATION_FAILED"
                ),
                "error_message": str(exc),
            }

        # ----------------------------------------------------
        # Deterministic validation
        # ----------------------------------------------------

        validation = self._validate_assessment(
            assessment=assessment,
            expected_question_count=question_count,
        )

        # One automatic repair attempt when the model output
        # fails deterministic structural validation.
        if not validation["valid"]:
            logger.warning(
                "Assessment structure invalid; attempting one repair. Errors: %s",
                validation.get("errors", []),
            )

            try:
                repair_prompt = (
                    generation_prompt
                    + "\\n\\nSTRUCTURAL VALIDATION REPAIR REQUIRED.\\n"
                    + "Your previous assessment failed these structural checks:\\n"
                    + "\\n".join(
                        f"- {error}"
                        for error in validation.get("errors", [])
                    )
                    + "\\nRegenerate the COMPLETE assessment. "
                    "Correct every listed issue. Return exactly the required "
                    "number of questions, exactly four non-empty distinct "
                    "options per question, a valid correct_option from 1 to 4, "
                    "non-empty question text, and the required structured format. "
                    "Return only the corrected structured assessment."
                )

                repaired_assessment: MCQAssessment = self.model.invoke(
                    repair_prompt
                )
                repaired_validation = self._validate_assessment(
                    assessment=repaired_assessment,
                    expected_question_count=question_count,
                )

                if repaired_validation["valid"]:
                    assessment = repaired_assessment
                    validation = repaired_validation
                    logger.info(
                        "Assessment passed structural validation after repair."
                    )
                else:
                    validation = repaired_validation
                    logger.error(
                        "Automatic assessment repair still failed: %s",
                        validation.get("errors", []),
                    )

            except Exception as repair_exc:
                logger.exception("Automatic assessment repair attempt failed.")
                validation = {
                    **validation,
                    "errors": list(validation.get("errors", []))
                    + [f"Automatic repair attempt failed: {repair_exc}"],
                }

        if not validation["valid"]:
            validation_errors = validation.get("errors", [])
            logger.error(
                "Assessment structural validation failed: %s",
                validation_errors,
            )

            return {
                **state,
                "status": "error",
                "error_code": "ASSESSMENT_VALIDATION_FAILED",
                "error_message": (
                    "Generated assessment failed structural validation. "
                    + " ".join(validation_errors)
                ),
                "validation_status": "failed",
                "validation_errors": validation_errors,
            }

        # ----------------------------------------------------
        # Normalize generated questions
        # ----------------------------------------------------

        questions = []

        for index, question in enumerate(
            assessment.questions,
            start=1,
        ):

            questions.append(
                {
                    "question_number": index,

                    "question": (
                        question.question.strip()
                    ),

                    "options": [
                        option.strip()
                        for option in question.options
                    ],

                    "correct_option": (
                        question.correct_option
                    ),

                    "difficulty": (
                        question.difficulty.strip()
                        or "medium"
                    ),

                    "marks": marks_per_question,

                    "explanation": (
                        question.explanation.strip()
                    ),
                }
            )

        # ----------------------------------------------------
        # Store assessment in state
        # ----------------------------------------------------

        return {
            **state,

            "questions": questions,

            "answer_key": [
                {
                    "question_number": question[
                        "question_number"
                    ],
                    "correct_option": question[
                        "correct_option"
                    ],
                }
                for question in questions
            ],

            "marking_scheme": [
                {
                    "question_number": question[
                        "question_number"
                    ],
                    "marks": marks_per_question,
                }
                for question in questions
            ],

            # Source references are taken from system state,
            # never invented by the LLM.
            "source_references": source_references,

            "validation_status": "passed",
            "validation_errors": [],

            "assessment_review_attempts": attempt,

            "approval_required": False,
            "approval_type": "assessment",
            "approval_status": "not_ready",

            "status": (
                "assessment_ready_for_review"
            ),

            "assessment_message": (
                f"MCQ assessment generated successfully "
                f"with {question_count} questions for "
                f"{total_marks} total marks. "
                f"Assessment Review Agent will verify it."
            ),

            "metadata": {
                **state.get(
                    "metadata",
                    {}
                ),

                "assessment_title": (
                    assessment.assessment_title
                ),

                "assessment_instructions": (
                    assessment.instructions
                ),

                "marks_per_question": (
                    marks_per_question
                ),

                "generation_mode": (
                    generation_mode
                ),

                "generation_attempt": attempt,
            },
        }

    # ========================================================
    # HELPERS
    # ========================================================

    @staticmethod
    def _get_task_input(
        task: Task,
    ) -> dict[str, Any]:
        """Safely extract task input."""

        if isinstance(
            task.input_data,
            dict,
        ):
            return task.input_data

        return {}

    @staticmethod
    def _clean(
        value: Any,
    ) -> str | None:
        """Normalize optional string values."""

        if value is None:
            return None

        value = str(value).strip()

        return value or None

    # ========================================================
    # STRUCTURAL VALIDATION
    # ========================================================

    @staticmethod
    def _validate_assessment(
        assessment: MCQAssessment,
        expected_question_count: int,
    ) -> dict[str, Any]:
        """
        Deterministic structural validation.

        Semantic correctness is intentionally handled by the
        independent Assessment Review Agent.
        """

        errors: list[str] = []

        questions = assessment.questions

        # ----------------------------------------------------
        # Question count
        # ----------------------------------------------------

        if len(questions) != expected_question_count:

            errors.append(
                f"Expected {expected_question_count} "
                f"questions but received "
                f"{len(questions)}."
            )

        # ----------------------------------------------------
        # Individual questions
        # ----------------------------------------------------

        seen_questions: set[str] = set()

        for index, question in enumerate(
            questions,
            start=1,
        ):

            # Four options
            if len(question.options) != 4:

                errors.append(
                    f"Question {index} must have "
                    f"exactly 4 options."
                )

            # Empty options
            for option_index, option in enumerate(
                question.options,
                start=1,
            ):

                if not option.strip():

                    errors.append(
                        f"Question {index}, "
                        f"option {option_index} is empty."
                    )

            # Duplicate options
            normalized_options = [
                option.strip().lower()
                for option in question.options
            ]

            if (
                len(set(normalized_options))
                != len(normalized_options)
            ):

                errors.append(
                    f"Question {index} contains "
                    f"duplicate options."
                )

            # Correct option
            if not (
                1 <= question.correct_option <= 4
            ):

                errors.append(
                    f"Question {index} has an invalid "
                    f"correct_option."
                )

            # Question text
            question_text = (
                question.question.strip()
            )

            if not question_text:

                errors.append(
                    f"Question {index} is empty."
                )

                continue

            # Duplicate question detection
            normalized_question = (
                " ".join(
                    question_text
                    .lower()
                    .split()
                )
            )

            if (
                normalized_question
                in seen_questions
            ):

                errors.append(
                    f"Question {index} is a duplicate."
                )

            seen_questions.add(
                normalized_question
            )

        return {
            "valid": not errors,
            "errors": errors,
        }


# ============================================================
# BACKWARD-COMPATIBLE FUNCTION
# ============================================================

_assessment_agent = AssessmentAgent()


def assessment_agent(
    state: TCOState,
    task: Task | None = None,
) -> TCOState:
    """
    Backward-compatible function for existing graph code.
    """

    return _assessment_agent.run(
        state,
        task,
    )