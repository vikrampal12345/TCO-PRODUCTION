from backend.agents.assessment_agent import AssessmentAgent
from backend.core.task import Task
from backend.tools.google_forms import GoogleFormsTool


# ============================================================
# 1. Local LLM -> Assessment Agent
# ============================================================

agent = AssessmentAgent()

state = {
    "teacher_request": "Create a 5 question MCQ test on SQL basics.",
    "class_level": "BTech 1st Year",
    "subject": "DBMS",
    "chapter": "SQL Basics",
    "topic": "SQL",
    "marks": 5,
    "question_count": 5,

    # We are intentionally testing direct LLM generation here.
    # No RAG/source is required for this test.
    "generation_mode": "llm_generated",

    "status": "started",
}


task = Task(
    capability="assessment.create",
    input_data={
        "teacher_request": "Create a 5 question MCQ test on SQL basics.",
        "class_level": "BTech 1st Year",
        "subject": "DBMS",
        "chapter": "SQL Basics",
        "topic": "SQL",
        "marks": 5,
        "question_count": 5,
        "generation_mode": "llm_generated",
        "requested_source": "",
        "source_preference": "general_knowledge",
        "source_url": "",
    },
)


print("\n========================================")
print("STEP 1: LOCAL LLM GENERATING QUESTIONS")
print("========================================")

state = agent.run(state, task)

if state.get("status") != "assessment_ready_for_review":
    print("Assessment generation failed.")
    print("Status:", state.get("status"))
    print("Error:", state.get("error_message"))
    raise SystemExit(1)


questions = state.get("questions", [])

print("\nGenerated Questions:")
print("----------------------------------------")

for i, question in enumerate(questions, start=1):

    print(f"\nQ{i}. {question['question']}")

    for option_number, option in enumerate(
        question["options"],
        start=1,
    ):
        correct = ""

        if option_number == question["correct_option"]:
            correct = "  <-- CORRECT"

        print(f"   {option_number}. {option}{correct}")


# ============================================================
# 2. EXACT SAME QUESTIONS -> Google Forms
# ============================================================

print("\n========================================")
print("STEP 2: SENDING SAME QUESTIONS TO GOOGLE FORM")
print("========================================")

forms_tool = GoogleFormsTool()

form_result = forms_tool.execute(
    title="TCO - SQL Basics Test",
    description="Generated by TCO Local LLM",
    questions=questions,  # IMPORTANT: exact LLM output
)

if not form_result.success:
    print("\nGoogle Form creation failed.")
    print("Error Code:", form_result.error_code)
    print("Error:", form_result.error_message)
    raise SystemExit(1)


# ============================================================
# 3. RESULT
# ============================================================

print("\n========================================")
print("GOOGLE FORM CREATED")
print("========================================")

print("Form ID:", form_result.data.get("form_id"))
print("Title:", form_result.data.get("title"))

print("\nResponder URL:")
print(form_result.data.get("responder_url"))

print("\nEdit URL:")
print(form_result.data.get("edit_url"))


# ============================================================
# 4. SHOW EXACT DATA SENT TO GOOGLE FORMS
# ============================================================

print("\n========================================")
print("EXACT QUESTIONS SENT TO GOOGLE FORMS")
print("========================================")

for i, question in enumerate(questions, start=1):

    print(f"\nQ{i}. {question['question']}")

    print("Options:")

    for option_number, option in enumerate(
        question["options"],
        start=1,
    ):
        print(f"   {option_number}. {option}")

    print(
        "Correct Option:",
        question["correct_option"],
    )


print("\n========================================")
print("LLM → GOOGLE FORMS TEST PASSED")
print("========================================")